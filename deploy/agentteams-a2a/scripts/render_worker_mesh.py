#!/usr/bin/env python3
"""Render one isolated Agent360 A2A worker per agent in a multi-agent QwenPaw instance.

Example:
  render_worker_mesh.py --instance gm --qwenpaw-container qwenpaw-gm-x --network net-x \
    --agents default,team,supplier,customer > /opt/agent360-a2a/docker-compose.worker.yml
"""
import argparse
import json
import re
import sys

AGENT_RE = re.compile(r"^[a-z0-9][a-z0-9_-]{0,62}$")


def render(instance, agents, container, network, origin_ip="100.77.205.126", domain="agentteams-gateway.hmz.one",
           max_depth=2, circuit_max=3, circuit_window=900):
    if not AGENT_RE.fullmatch(instance) or not agents or any(not AGENT_RE.fullmatch(a) for a in agents):
        raise ValueError("instance and agents must be lowercase identifiers")
    if len(agents) != len(set(agents)):
        raise ValueError("duplicate agents")
    senders = [f"@agent360-a2a:{domain}"] + [f"@{instance}-{a}:{domain}" for a in agents]
    out = ["# Generated by render_worker_mesh.py. Edit inputs, not individual services.", "services:"]
    for agent in agents:
        local = f"{instance}-{agent}"
        health = (
            "import sqlite3,datetime as d;"
            f"r=sqlite3.connect('/state/{local}/worker.db').execute(\"select v from a2a_kv where k='heartbeat'\").fetchone();"
            "t=d.datetime.strptime(r[0],'%Y-%m-%dT%H:%M:%SZ');"
            "exit(0 if (d.datetime.utcnow()-t).total_seconds()<120 else 1)"
        )
        env = {
            "A2A_MATRIX_CRED": f"/secrets/{local}.matrix.json",
            "A2A_AGENT_REF": f"agent://{instance}/{agent}",
            "A2A_QWENPAW_URL": f"http://{container}:8088",
            "A2A_QWENPAW_AGENT": agent,
            "A2A_QWENPAW_AUTH_FILE": f"/secrets/qwenpaw-{instance}.auth.json",
            "A2A_ALLOWED_SENDERS": ",".join(senders),
            "A2A_STATE_DIR": f"/state/{local}",
            "A2A_MAX_CONCURRENCY": "2",
            "A2A_HEARTBEAT_SECONDS": "45",
            "A2A_MATRIX_ORIGIN_IP": origin_ip,
            "A2A_SYNC_TIMEOUT_MS": "20000",
            "A2A_MAX_DEPTH": str(max_depth),
            "A2A_CIRCUIT_MAX": str(circuit_max),
            "A2A_CIRCUIT_WINDOW_SECONDS": str(circuit_window),
        }
        out += [
            f"  agent360-a2a-worker-{local}:",
            "    image: python:3.12-alpine",
            f"    container_name: agent360-a2a-worker-{local}",
            "    restart: unless-stopped",
            "    working_dir: /app",
            '    command: ["python", "-u", "worker_adapter.py"]',
            "    environment:",
        ]
        out += [f"      {k}: {json.dumps(v)}" for k, v in env.items()]
        out += [
            "    volumes:",
            "      - /opt/agent360-a2a/app:/app:ro",
            "      - /opt/agent360-a2a/secrets:/secrets:ro",
            "      - /opt/agent360-a2a/state:/state",
            "    networks: [qwenpaw]",
            "    healthcheck:",
            f"      test: {json.dumps(['CMD', 'python', '-c', health], ensure_ascii=False)}",
            "      interval: 60s",
            "      timeout: 10s",
            "      retries: 3",
            "      start_period: 60s",
        ]
    out += ["networks:", "  qwenpaw:", "    external: true", f"    name: {network}"]
    return "\n".join(out) + "\n"


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--instance", required=True)
    p.add_argument("--agents", required=True)
    p.add_argument("--qwenpaw-container", required=True)
    p.add_argument("--network", required=True)
    p.add_argument("--origin-ip", default="100.77.205.126")
    p.add_argument("--max-depth", type=int, default=2)
    p.add_argument("--circuit-max", type=int, default=3)
    p.add_argument("--circuit-window", type=int, default=900)
    a = p.parse_args(argv)
    agents = [x.strip() for x in a.agents.split(",") if x.strip()]
    sys.stdout.write(render(a.instance, agents, a.qwenpaw_container, a.network, a.origin_ip,
                            max_depth=a.max_depth, circuit_max=a.circuit_max, circuit_window=a.circuit_window))


if __name__ == "__main__":
    main()
