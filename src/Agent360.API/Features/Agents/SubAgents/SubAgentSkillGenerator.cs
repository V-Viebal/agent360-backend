using System.Text;

namespace Agent360.API.Features.Agents.SubAgents;

public static class SubAgentSkillGenerator
{
    public const string SkillName = "agent360-subagents";

    /// <summary>Stable fingerprint of the generated skill, ignoring the generation timestamp.</summary>
    public static string Fingerprint(string content)
    {
        var normalized = System.Text.RegularExpressions.Regex.Replace(content, @"Generated by Agent360 at [^.]+UTC\.", "Generated by Agent360.");
        return Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(Encoding.UTF8.GetBytes(normalized)));
    }

    public static string Generate(string parentAgentId, IReadOnlyList<SubAgentBinding> bindings)
    {
        var active = bindings.Where(b => b.Enabled).OrderBy(b => b.ChildAgentId).ToList();
        var sb = new StringBuilder();
        sb.AppendLine("---");
        sb.AppendLine($"name: {SkillName}");
        sb.AppendLine("description: Discover, delegate, monitor, and accept work from configured Agent360 sub-agents.");
        sb.AppendLine("status: active");
        sb.AppendLine("owner: agent360");
        sb.AppendLine("---");
        sb.AppendLine();
        sb.AppendLine("# Agent360 Sub-Agent Orchestration");
        sb.AppendLine();
        sb.AppendLine($"Parent agent: `{parentAgentId}`. Generated by Agent360 at {DateTimeOffset.UtcNow:yyyy-MM-dd HH:mm:ss} UTC. Do not edit manually; Agent360 regenerates this file when bindings change.");
        sb.AppendLine();
        sb.AppendLine("## Available Sub-Agents");
        sb.AppendLine();
        if (active.Count == 0)
        {
            sb.AppendLine("_No sub-agents are currently bound. Do not delegate to other agents; complete the work yourself._");
        }
        else
        {
            sb.AppendLine("| Agent | Role | Capabilities | Modes | Timeout | Max parallel |");
            sb.AppendLine("|---|---|---|---|---|---|");
            foreach (var b in active)
            {
                sb.AppendLine($"| {b.ChildAgentId} | {b.Role} | {string.Join(", ", b.Capabilities)} | {string.Join(", ", b.AllowedModes)} | {b.TimeoutSeconds}s | {b.MaxParallelTasks} |");
            }
        }

        sb.AppendLine();
        sb.AppendLine("## When to Delegate");
        sb.AppendLine();
        sb.AppendLine("- Delegate only to agents listed above and only when the task matches a listed capability.");
        sb.AppendLine("- Never delegate to an agent that is not in the table, even if `list_agents` shows it.");
        sb.AppendLine("- Do not delegate secrets, credentials, tokens, or destructive actions.");
        sb.AppendLine("- Keep each delegated objective narrow and verifiable.");
        sb.AppendLine("- Sub-agents must not delegate further (max depth = 1). Never ask a sub-agent to call you back.");
        sb.AppendLine();
        sb.AppendLine("## How to Delegate");
        sb.AppendLine();
        sb.AppendLine("- Use `chat_with_agent(to_agent, text)` for short synchronous questions (mode `sync`).");
        sb.AppendLine("- Use `submit_to_agent(to_agent, text, task_timeout)` for long-running work (mode `async`); keep the returned `TASK_ID`.");
        sb.AppendLine("- Use `check_agent_task(task_id)` to monitor background work. Wait at least 30 seconds between checks.");
        sb.AppendLine("- Respect each agent's timeout and max-parallel limit from the table.");
        sb.AppendLine();
        sb.AppendLine("## Required Delegation Format");
        sb.AppendLine();
        sb.AppendLine("Every delegated task text must include these sections:");
        sb.AppendLine();
        sb.AppendLine("1. Objective");
        sb.AppendLine("2. Context");
        sb.AppendLine("3. Constraints");
        sb.AppendLine("4. Expected output");
        sb.AppendLine("5. Acceptance criteria");
        sb.AppendLine("6. Evidence required");
        sb.AppendLine();
        sb.AppendLine("## Acceptance");
        sb.AppendLine();
        sb.AppendLine("Before using a sub-agent result:");
        sb.AppendLine();
        sb.AppendLine("1. Compare output with every acceptance criterion.");
        sb.AppendLine("2. Mark each criterion as pass/fail/unknown.");
        sb.AppendLine("3. Reject if any required criterion fails.");
        sb.AppendLine("4. Retry at most once with specific feedback.");
        sb.AppendLine("5. Report accepted results and remaining risks to the user.");
        sb.AppendLine();
        sb.AppendLine("Agent360 records every `chat_with_agent` / `submit_to_agent` call in its delegation ledger for audit.");
        return sb.ToString();
    }
}
